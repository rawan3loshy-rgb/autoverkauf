import type { Vehicle, VehicleImage } from '@/lib/types';

/**
 * Demo-Bestand für die Autokunst-Präsentation.
 *
 * Alle Fahrzeuge, Preise und Fahrzeughistorien sind fiktiv und dienen ausschließlich
 * der Demonstration. Verbrauchs- und Emissionsangaben sind Demo-Werte.
 *
 * Die Struktur entspricht bewusst dem, was später eine API liefern würde –
 * der Zugriff läuft ausschließlich über `lib/vehicle-repository.ts`.
 */

type Role = VehicleImage['role'];

const ROLE_LABEL: Record<Role, string> = {
  exterieur: 'Frontansicht',
  seite: 'Seitenansicht',
  heck: 'Heckansicht',
  interieur: 'Innenraum',
  cockpit: 'Cockpit',
  raeder: 'Räder',
  detail: 'Detailaufnahme',
};

/** Baut den Bildsatz eines Fahrzeugs aus der Dateinamenskonvention. */
function gallery(slug: string, name: string, roles: Role[]): VehicleImage[] {
  return roles.map((role) => ({
    src: `/vehicles/${slug}/${role}.jpg`,
    alt: `${name} – ${ROLE_LABEL[role]}`,
    role,
  }));
}

